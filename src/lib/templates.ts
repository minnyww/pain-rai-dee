const drawers: Record<string, (t: Tools) => void> = {
  unicorn, dino, space, ocean, garden, butterfly, cat, castle, robot, fruit,
}

export function drawTemplate(ctx: Ctx, id: string, w: number, h: number) {
  ctx.save()
  ctx.scale(w / CANVAS_W, h / CANVAS_H)
  ctx.strokeStyle = INK
  ctx.fillStyle = INK
  ctx.lineWidth = 5
  ctx.lineCap = 'round'
  ctx.lineJoin = 'round'
  ;(drawers[id] ?? fruit)(makeTools(ctx))
  ctx.strokeStyle = '#dfe2f6'
  ctx.lineWidth = 6
  ctx.beginPath(); ctx.roundRect(20, 20, CANVAS_W - 40, CANVAS_H - 40, 34); ctx.stroke()
  ctx.restore()
}
