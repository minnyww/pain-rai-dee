// Line art for the coloring pages, authored on a fixed 900x700 grid so the
// coordinates can be hand-tuned like a coloring book. drawTemplate scales the
// grid to whatever canvas size it is given.
type Ctx = CanvasRenderingContext2D
const TAU = Math.PI * 2
const CANVAS_W = 900
const CANVAS_H = 700
const INK = '#33354f'

type Tools = {
  S: (d: string) => void
  ring: (x: number, y: number, r: number, ry?: number) => void
  dot: (x: number, y: number, r: number, shine?: boolean) => void
  rrect: (x: number, y: number, w: number, h: number, r: number) => void
  star: (x: number, y: number, r: number) => void
  heart: (x: number, y: number, s: number) => void
  daisy: (x: number, y: number, r0: number, r1: number, n?: number, half?: number) => void
  cloud: (x: number, y: number, s: number) => void
  mirrored: (fn: () => void) => void
}

function makeTools(ctx: Ctx): Tools {
  const S = (d: string) => ctx.stroke(new Path2D(d))
  const ring = (x: number, y: number, r: number, ry = r) => {
    ctx.beginPath(); ctx.ellipse(x, y, r, ry, 0, 0, TAU); ctx.stroke()
  }
  const dot = (x: number, y: number, r: number, shine = false) => {
    ctx.beginPath(); ctx.arc(x, y, r, 0, TAU); ctx.fill()
    if (shine) {
      ctx.save(); ctx.fillStyle = '#fff'
      ctx.beginPath(); ctx.arc(x - r * 0.32, y - r * 0.32, r * 0.3, 0, TAU); ctx.fill()
      ctx.restore()
    }
  }
  const rrect = (x: number, y: number, w: number, h: number, r: number) => {
    ctx.beginPath(); ctx.roundRect(x, y, w, h, r); ctx.stroke()
  }
  const star = (x: number, y: number, r: number) => {
    let d = ''
    for (let i = 0; i < 10; i++) {
      const a = -Math.PI / 2 + (i * Math.PI) / 5
      const rr = i % 2 ? r * 0.45 : r
      d += `${i ? 'L' : 'M'}${(x + Math.cos(a) * rr).toFixed(1)} ${(y + Math.sin(a) * rr).toFixed(1)}`
    }
    S(`${d}Z`)
  }
  const heart = (x: number, y: number, s: number) =>
    S(`M${x} ${y + s} C${x - 1.35 * s} ${y + 0.1 * s} ${x - 1.2 * s} ${y - 0.9 * s} ${x} ${y - 0.25 * s}` +
      ` C${x + 1.2 * s} ${y - 0.9 * s} ${x + 1.35 * s} ${y + 0.1 * s} ${x} ${y + s}Z`)
  const daisy = (x: number, y: number, r0: number, r1: number, n = 8, half = 0.3) => {
    for (let i = 0; i < n; i++) {
      const a = (i / n) * TAU - Math.PI / 2
      const p = (r: number, da: number) => `${(x + Math.cos(a + da) * r).toFixed(1)} ${(y + Math.sin(a + da) * r).toFixed(1)}`
      S(`M${p(r0, -half)} Q${p(r1, -half * 0.4)} ${p(r1, 0)} Q${p(r1, half * 0.4)} ${p(r0, half)}`)
    }
    ring(x, y, r0)
  }
  const cloud = (x: number, y: number, s: number) => {
    ctx.save(); ctx.translate(x - 50 * s, y - 30 * s); ctx.scale(s, s)
    S('M25 52 C10 52 4 38 14 30 C8 18 20 6 32 12 C38 2 56 2 62 12 C76 6 90 16 86 30 C96 36 92 52 78 52 Z')
    ctx.restore()
  }
  const mirrored = (fn: () => void) => {
    ctx.save(); ctx.translate(CANVAS_W, 0); ctx.scale(-1, 1); fn(); ctx.restore()
  }
  return { S, ring, dot, rrect, star, heart, daisy, cloud, mirrored }
}

